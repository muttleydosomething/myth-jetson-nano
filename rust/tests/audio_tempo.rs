//! Tempo is a response transform: never resample the voice or prepare it again.
use chatterbox_rs::{
    audio_output::{self, Format},
    npy::F32Npy,
};
fn tone(n: usize) -> F32Npy {
    F32Npy {
        shape: vec![1, n],
        values: (0..n)
            .map(|i| 0.2 * (std::f32::consts::TAU * 440. * i as f32 / 24000.).sin())
            .collect(),
    }
}
#[test]
fn tempo_processing_replays_and_preserves_pitch() {
    let input = tone(24000);
    for speed in [0.5, 0.75, 1., 1.5, 2.] {
        let output = audio_output::tempo(&input, speed, || false).unwrap();
        assert_eq!(
            output.values.len(),
            (24000f64 / speed).round_ties_even() as usize
        );
        assert_eq!(output.shape, vec![1, output.values.len()]);
        if speed == 1. {
            assert_eq!(input.values, output.values);
        }
        // Ignore the analysis edges; zero crossings measure pitch independently
        // of the phase-vocoder implementation and would detect resampling.
        let middle = &output.values[2048..output.values.len() - 2048];
        let crossings = middle
            .windows(2)
            .filter(|p| p[0] <= 0. && p[1] > 0.)
            .count();
        let hz = crossings as f64 * 24000. / middle.len() as f64;
        assert!((hz - 440.).abs() < 4., "speed={speed}, pitch={hz}");
        let other = tone(8193);
        audio_output::tempo(&other, 1.3, || false).unwrap();
        assert_eq!(
            output.values,
            audio_output::tempo(&input, speed, || false).unwrap().values
        );
        if let Ok(root) = std::env::var("CHATTERBOX_TEMPO_PROOF_DIR") {
            std::fs::write(
                format!("{root}/tone-{speed}.wav"),
                audio_output::encode(&output, Format::Wav, || false).unwrap(),
            )
            .unwrap();
        }
    }
}
#[test]
fn tempo_cancellation_and_admission() {
    let input = tone(24000);
    for bad in [0., -1., f64::NAN, f64::INFINITY, f64::NEG_INFINITY] {
        assert!(audio_output::validate_speed(bad).is_err());
        assert!(audio_output::tempo(&input, bad, || false).is_err());
    }
    // Both length overflow and a speed yielding no samples fail explicitly.
    for bad in [f64::MIN_POSITIVE, f64::MAX] {
        assert!(audio_output::tempo(&input, bad, || false).is_err());
    }
    let mut calls = 0;
    assert!(audio_output::tempo(&input, 0.5, || {
        calls += 1;
        calls > 6
    })
    .unwrap_err()
    .contains("cancelled"));
    assert!(calls > 6);
    let mut malformed = tone(2);
    malformed.values[0] = f32::NAN;
    assert!(audio_output::tempo(&malformed, 1., || false).is_err());
    malformed = tone(2);
    malformed.shape = vec![2, 1];
    assert!(audio_output::tempo(&malformed, 1.5, || false).is_err());
    malformed = tone(2);
    malformed.shape = vec![1, 3];
    assert!(audio_output::tempo(&malformed, 1.5, || false).is_err());
    assert!(audio_output::tempo(&tone(0), 1., || false).is_err());
}
#[test]
fn tempo_handles_silence_short_audio_and_rounds_ties_even() {
    for n in [1, 2, 3, 511, 512, 513, 2048, 2049] {
        for speed in [0.5, 1.5, 2.] {
            let input = F32Npy {
                shape: vec![1, n],
                values: vec![0.; n],
            };
            let expected = (n as f64 / speed).round_ties_even() as usize;
            let result = audio_output::tempo(&input, speed, || false);
            if expected == 0 {
                assert!(result.is_err());
                continue;
            }
            let output = result.unwrap();
            assert_eq!(output.values.len(), expected);
            assert!(output.values.iter().all(|v| *v == 0.));
        }
    }
}
// External oracle files are generated by the deployed librosa, not this crate.
#[test]
#[ignore = "requires independently captured deployed librosa oracle"]
fn tempo_deployed_oracle() {
    let root = std::env::var("CHATTERBOX_TEMPO_ORACLE_DIR").unwrap();
    let root = std::path::Path::new(&root);
    let cases: serde_json::Value =
        serde_json::from_slice(&std::fs::read(root.join("oracle.json")).unwrap()).unwrap();
    for case in cases["cases"].as_array().unwrap() {
        let input =
            F32Npy::from_bytes(&std::fs::read(root.join(case["input"].as_str().unwrap())).unwrap())
                .unwrap();
        let expected = F32Npy::from_bytes(
            &std::fs::read(root.join(case["output"].as_str().unwrap())).unwrap(),
        )
        .unwrap();
        let actual =
            audio_output::tempo(&input, case["speed"].as_f64().unwrap(), || false).unwrap();
        assert_eq!(actual.shape, expected.shape);
        let power: f64 = expected.values.iter().map(|v| (*v as f64).powi(2)).sum();
        let noise: f64 = actual
            .values
            .iter()
            .zip(&expected.values)
            .map(|(a, b)| (*a as f64 - *b as f64).powi(2))
            .sum();
        let snr = 10. * (power / noise.max(1e-30)).log10();
        let max_error = actual
            .values
            .iter()
            .zip(&expected.values)
            .map(|(a, b)| (a - b).abs())
            .fold(0f32, f32::max);
        assert!(actual.values.iter().all(|v| v.is_finite()));
        assert!(
            power == 0. && noise == 0. || snr > 40.,
            "{}: SNR={snr}, max={max_error}",
            case["name"]
        );
        println!("{}: SNR={snr}, max={max_error}", case["name"]);
    }
}
